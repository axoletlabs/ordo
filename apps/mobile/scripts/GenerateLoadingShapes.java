import androidx.graphics.shapes.*;
import java.lang.reflect.Proxy;
import java.util.*;

public class GenerateLoadingShapes {
  record Point(float x, float y, float rounding) {}
  static Point p(float x, float y, float rounding) { return new Point(x, y, rounding); }

  static RoundedPolygon polygon(Point[] points, int reps, boolean mirror) {
    var vertices = new ArrayList<Float>();
    var rounding = new ArrayList<CornerRounding>();
    int sections = mirror ? reps * 2 : reps;
    double firstAngle = Math.atan2(points[0].y - .5, points[0].x - .5);
    double sectionAngle = 2 * Math.PI / sections;
    for (int section = 0; section < sections; section++) {
      for (int index = 0; index < points.length; index++) {
        int i = mirror && section % 2 == 1 ? points.length - 1 - index : index;
        if (mirror && i == 0 && section % 2 == 1) continue;
        Point point = points[i];
        double angle = Math.atan2(point.y - .5, point.x - .5);
        double distance = Math.hypot(point.x - .5, point.y - .5);
        double a = sectionAngle * section + (mirror && section % 2 == 1
          ? sectionAngle - angle + 2 * firstAngle : angle);
        vertices.add((float)(Math.cos(a) * distance + .5));
        vertices.add((float)(Math.sin(a) * distance + .5));
        rounding.add(new CornerRounding(point.rounding, 0));
      }
    }
    float[] v = new float[vertices.size()];
    for (int i = 0; i < v.length; i++) v[i] = vertices.get(i);
    return RoundedPolygonKt.RoundedPolygon(v, CornerRounding.Unrounded, rounding, .5f, .5f);
  }

  static RoundedPolygon transform(RoundedPolygon shape, double angle, float scaleY) {
    // PointTransformer returns Kotlin's packed inline Point (x in the high bits).
    var transformer = (PointTransformer) Proxy.newProxyInstance(
      PointTransformer.class.getClassLoader(), new Class<?>[]{PointTransformer.class},
      (proxy, method, args) -> {
        float x = (Float)args[0], y = (Float)args[1] * scaleY;
        float nx = (float)(x * Math.cos(angle) - y * Math.sin(angle));
        float ny = (float)(x * Math.sin(angle) + y * Math.cos(angle));
        return ((long)Float.floatToRawIntBits(nx) << 32) | (Float.floatToRawIntBits(ny) & 0xffffffffL);
      });
    return shape.transformed(transformer);
  }

  static String coordinates(List<Cubic> cubics) {
    var values = new ArrayList<String>();
    for (Cubic c : cubics) {
      for (float f : new float[]{c.getAnchor0X(), c.getAnchor0Y(), c.getControl0X(), c.getControl0Y(),
          c.getControl1X(), c.getControl1Y(), c.getAnchor1X(), c.getAnchor1Y()}) {
        values.add(String.format(Locale.ROOT, "%.5f", f));
      }
    }
    return "[" + String.join(",", values) + "]";
  }

  public static void main(String[] args) {
    var companion = RoundedPolygon.Companion;
    RoundedPolygon[] shapes = {
      polygon(new Point[]{p(.193f,.277f,.053f), p(.176f,.055f,.053f)}, 10, false),
      transform(ShapesKt.star(companion,9,1,.8f,new CornerRounding(.5f,0)), -Math.PI/2, 1),
      polygon(new Point[]{p(.5f,-.009f,.172f),p(1.030f,.365f,.164f),p(.828f,.970f,.169f)},1,true),
      polygon(new Point[]{p(.961f,.039f,.426f),p(1.001f,.428f,0),p(1,.609f,1)},2,true),
      ShapesKt.star(companion,8,1,.8f,new CornerRounding(.15f,0)),
      polygon(new Point[]{p(1.237f,1.236f,.258f),p(.5f,.918f,.233f)},4,false),
      transform(ShapesKt.circle(companion), -Math.PI/4, .64f),
    };
    float scale = 1;
    for (int i = 0; i < shapes.length; i++) {
      shapes[i] = shapes[i].normalized();
      float[] b = shapes[i].calculateBounds();
      float[] m = shapes[i].calculateMaxBounds(new float[4]);
      scale = Math.min(scale, Math.max((b[2]-b[0])/(m[2]-m[0]), (b[3]-b[1])/(m[3]-m[1])));
    }
    System.out.println("/* Copyright 2024 The Android Open Source Project; SPDX-License-Identifier: Apache-2.0 */");
    System.out.println("// Generated by scripts/GenerateLoadingShapes.java using AndroidX Graphics Shapes 1.0.1.");
    System.out.println("// Adapted from MaterialShapes.kt; see material-loading.LICENSE for attribution and terms.");
    System.out.println("// SoftBurst → Cookie9 → Pentagon → Pill → Sunny → Cookie4 → Oval → SoftBurst.");
    System.out.println("export const LOADING_SHAPE_SCALE = " + scale + ";");
    System.out.println("export const LOADING_MORPHS: readonly { from: readonly number[]; to: readonly number[] }[] = [");
    for (int i = 0; i < shapes.length; i++) {
      Morph morph = new Morph(shapes[i], shapes[(i+1)%shapes.length]);
      System.out.println("  { from: " + coordinates(morph.asCubics(0)) + ",\n    to: " + coordinates(morph.asCubics(1)) + " },");
    }
    System.out.println("];");
  }
}
