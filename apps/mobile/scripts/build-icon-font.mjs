/**
 * Regenerates the icon subset after adding or changing an icon:
 *
 *   node --experimental-strip-types scripts/build-icon-font.mjs
 *
 * Writes src/theme/material-icon-glyphs.ts and assets/fonts/MaterialIcons-Ordo.ttf
 * (only the glyphs the app references, from @expo/vector-icons' MaterialIcons).
 * Needs fontTools' pyftsubset on PATH, or PYFTSUBSET=/path/to/pyftsubset.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { MATERIAL_ICONS_TTF, MOBILE_ROOT, requiredGlyphs } from "./icon-font-scan.mjs";

const glyphs = requiredGlyphs();
const table = [...glyphs].map(([name, code]) => `  ${JSON.stringify(name)}: ${code},`).join("\n");
writeFileSync(
  path.join(MOBILE_ROOT, "src/theme/material-icon-glyphs.ts"),
  `// Generated by scripts/build-icon-font.mjs. Do not edit by hand.\n` +
    `export const MATERIAL_ICON_GLYPHS: Record<string, number> = {\n${table}\n};\n`,
);

const output = path.join(MOBILE_ROOT, "assets/fonts/MaterialIcons-Ordo.ttf");
execFileSync(process.env.PYFTSUBSET || "pyftsubset", [
  MATERIAL_ICONS_TTF,
  `--unicodes=${[...glyphs.values()].map((code) => code.toString(16)).join(",")}`,
  // Glyphs are drawn by codepoint; the ligature table only serves web CSS.
  "--layout-features=",
  "--no-glyph-names",
  "--notdef-outline",
  "--name-IDs=*",
  "--name-legacy",
  `--output-file=${output}`,
], { stdio: "inherit" });
console.log(`${glyphs.size} icons → ${path.relative(MOBILE_ROOT, output)}`);
